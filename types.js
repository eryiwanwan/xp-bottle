/* 倾向类型引擎
   输入：答案数组（-1 未答 / 0 跳过 / 1 雷区 / 2 好奇 / 3 喜欢 / 4 满溢）、词表、位置
   输出：三个维度 + 类型名 + 描述 + 坑 + 三条建议

   这不是诊断，只是把一堆答案归纳成一个方便记住的说法。 */

(function (global) {

  var ROLES = [
    { k: 'dom', n: '主导', pn: '主导位', d: '你通常是安排的那一方' },
    { k: 'sub', n: '服从', pn: '服从位', d: '你通常是被安排的那一方' },
    { k: 'switch', n: '两边都行', pn: '交换位', d: '看人、看场合，位置会换' },
    { k: 'fantasy', n: '只是想想', pn: '幻想位', d: '目前都还在脑子里，还没打算实现' }
  ];

  var POWER = ['权力', '支配', '束缚', '调教'];

  var TYPE = {
    dom: [
      {
        n: '试笔者',
        d: '你在边界上蹑手蹑脚：想控制，但还没找到手感。',
        pit: '把「想要主导」误当成「必须强势」——这两件事差得很远。',
        tips: [
          '先挑一项成本最低的试一次，别从你最想要的那项开始。',
          '把「我想试试」和「我要」说成两句不同的话。',
          '主导是一种服务，不是一种权力，先问对方要什么。'
        ]
      },
      {
        n: '掌舵',
        d: '你清楚自己要什么，也愿意为对方的反应调整方向。',
        pit: '太依赖对方的反馈，容易在沉默里过度解读。',
        tips: [
          '每次开始前用一句话确认今天的位置，别靠默契。',
          '对方的沉默不等于同意，停下来问一次不丢人。',
          '记下对方主动提过的词，那比你猜的准。'
        ]
      },
      {
        n: '立法者',
        d: '你要的不只是动作，是一整套秩序：规则、称呼、后果。',
        pit: '规则越密，对方越难说出「今天不行」。',
        tips: [
          '规则写下来的时候，也写一条「随时可以暂停」。',
          '每三个月重写一次——人会变，契约也该变。',
          '留一个不设规则的晚上，看看对方本来是什么样。'
        ]
      }
    ],
    switch: [
      {
        n: '闲逛者',
        d: '两边都好奇，两边都还没扎根。',
        pit: '一直在试，没有一样试到底——广度会伪装成经验。',
        tips: [
          '选一项连续做三次再判断，一次不算数。',
          '把「我都行」换成「这次我想在哪边」。',
          '好奇心是入口，不是答案。'
        ]
      },
      {
        n: '潮汐',
        d: '你随对方的位置换位置。这是种能力，也很耗。',
        pit: '太会配合，最后没人知道你想要什么，包括你自己。',
        tips: [
          '每次至少说一次「这次我想要什么」，哪怕很小。',
          '配合是选择，不是义务，分不清就会累。',
          '找那种会主动问你想要什么的人。'
        ]
      },
      {
        n: '共谋者',
        d: '你们要的是一场双方都清楚规则的对局，谁在什么位置都行。',
        pit: '把「能配合」当成「没有底线」。',
        tips: [
          '角色可以换，但要明确谁在什么时候说话算数。',
          '交换位置的时候，给彼此一个明确的信号。',
          '每换一次位置，边界要重新对一遍。'
        ]
      }
    ],
    sub: [
      {
        n: '旁观者',
        d: '你在门口看，看得比谁都细。',
        pit: '把「看」当成「不参与」——其实你已经在参与了。',
        tips: [
          '把看到的写成一句具体的话给出去，比沉默有用。',
          '幻想不需要落地，但要说清它只是幻想。',
          '先分清「想被这样对待」和「想看这件事发生」。'
        ]
      },
      {
        n: '随行',
        d: '你想被带着走，但要看得见路。',
        pit: '不说出「再往下一点会更好」，对方只能猜。',
        tips: [
          '用刻度说话：「更重一点」「轻一点」，比形容词准。',
          '安全词不是不信任，是效率。',
          '事后那十分钟，比过程更能决定你要不要再来一次。'
        ]
      },
      {
        n: '归零',
        d: '你想把决定权整个交出去，越彻底越安心。',
        pit: '交出去之前没谈过「什么时候收回」。',
        tips: [
          '先定义收回的方式，再谈交出的程度。',
          '高强度项必须有第二个人知道，这不是扫兴。',
          '把「我信任你」换成「我信任这套流程」，后者更可靠。'
        ]
      }
    ]
  };

  function roleOf(k) {
    for (var i = 0; i < ROLES.length; i++) if (ROLES[i].k === k) return ROLES[i];
    return ROLES[2];
  }

  function analyze(ans, items, role) {
    var answered = 0, want = 0, no = 0, rel = 0, sum = 0, powerWant = 0;

    for (var i = 0; i < items.length; i++) {
      var lv = ans[i];
      if (lv > 0) answered++;
      if (lv >= 3) {
        want++;
        sum += lv - 2;                       /* 好奇=1 喜欢=2 满溢=3 */
        if (POWER.indexOf(items[i][1]) >= 0) powerWant++;
      }
      if (lv === 1) no++;
      if (lv === 2) rel++;
    }

    var I = want ? sum / (3 * want) : 0;
    var B = answered ? want / answered : 0;
    /* 雷区算满格边界，抵触算半格 */
    var C = answered ? (no + rel * 0.5) / answered : 0;
    var PW = want ? powerWant / want : 0;

    if (answered === 0) {
      return { empty: true, name: '空瓶', desc: '你什么都没放进去。', tips: [], dims: [] };
    }

    var r = roleOf(role);
    var band = I < 0.34 ? 0 : I < 0.67 ? 1 : 2;
    var table = r.k === 'fantasy' ? 'switch' : r.k;
    var t = TYPE[table][band];

    var prefix = C >= 0.38 ? '带刺的' : C <= 0.14 ? '留白的' : '';
    var prefixNote = C >= 0.38
      ? '你的雷区比想要的多——这不是保守，说明你清楚自己不要什么。'
      : C <= 0.14
        ? '你几乎没划雷区。可能是真的都行，也可能是还没遇到。'
        : '';
    var full = prefix + t.n;

    var pos = r.pn + ' · ' + ['浅', '中', '深'][band] + '度';

    var extra = '';
    if (r.k === 'fantasy') {
      extra = '你选的是「只是想想」——所以下面这些说的都是你的想象，不是你的履历。';
    } else if (PW >= 0.42) {
      extra = '你的答案里有 ' + Math.round(PW * 100) + '% 落在权力、支配、束缚这类；你要的核心不是身体，是位置。';
    } else if (PW <= 0.16) {
      extra = '你的答案里几乎没有权力类的东西；你要的是感受本身，不是谁在上面。';
    }

    return {
      role: r.k,
      roleName: r.n,
      band: band,
      bandName: ['浅', '中', '深'][band],
      name: full,
      base: t.n,
      desc: t.d,
      prefixNote: prefixNote,
      pit: t.pit,
      tips: t.tips,
      extra: extra,
      pos: pos,
      dims: [
        { k: '强度', v: I, hint: '你要多重' },
        { k: '广度', v: B, hint: '你想试多少种' },
        { k: '边界', v: C, hint: '你敢说多少不行' }
      ],
      powerRatio: PW
    };
  }

  global.XT = { analyze: analyze, ROLES: ROLES, TYPE: TYPE };
})(window);
